export const translations = { en, hi, te }

export function getUiLanguage(languageCode) {
  return translations[languageCode] ? languageCode : 'en'
}

export function translate(languageCode, key) {
  const lang = getUiLanguage(languageCode)
  return translations[lang][key] ?? translations.en[key] ?? key
}

export function translateSign(languageCode, signName) {
  const lang = getUiLanguage(languageCode)
  return translations[lang].signs?.[signName] ?? signName
}
